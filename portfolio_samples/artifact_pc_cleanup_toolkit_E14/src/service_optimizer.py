"""Windows service auditor and telemetry startup optimizer with rollback generation.
Strict zero em dash policy enforced.
"""
from typing import List, Dict, Any, Optional
from src.models import ServiceStartupType, ServiceAuditRecord, ServiceTuningRule
from src.config import WindowsOptimizerConfig


class WindowsServiceOptimizer:
    """Audits Windows background services and generates safe tuning and rollback scripts."""

    def __init__(self, config: Optional[WindowsOptimizerConfig] = None):
        self.config = config or WindowsOptimizerConfig()
        self.known_bloat_services: Dict[str, Dict[str, Any]] = {
            "DiagTrack": {
                "display": "Connected User Experiences and Telemetry",
                "category": "Telemetry",
                "recommended": ServiceStartupType.DISABLED,
                "reason": "Diagnostic telemetry service collecting diagnostic usage data."
            },
            "dmwappushservice": {
                "display": "Device Management Wireless Application Protocol Push",
                "category": "Telemetry",
                "recommended": ServiceStartupType.DISABLED,
                "reason": "WAP push message routing for telemetry and data collection."
            },
            "RetailDemo": {
                "display": "Retail Demo Service",
                "category": "Bloatware",
                "recommended": ServiceStartupType.DISABLED,
                "reason": "Retail store kiosk demonstration mode."
            },
            "XblAuthManager": {
                "display": "Xbox Live Auth Manager",
                "category": "Gaming Bloat",
                "recommended": ServiceStartupType.MANUAL,
                "reason": "Authentication for Xbox Live services on non-gaming workstations."
            }
        }

    def audit_service(
        self,
        service_name: str,
        current_startup: ServiceStartupType,
        current_status: str
    ) -> ServiceAuditRecord:
        """Audit single Windows service and evaluate safe optimization recommendation."""
        # Immutable system protection check
        if service_name in self.config.protected_services:
            return ServiceAuditRecord(
                service_name=service_name,
                display_name=service_name,
                current_startup=current_startup,
                current_status=current_status,
                recommended_startup=current_startup,
                is_safe_to_disable=False,
                category="Core OS Protected",
                reason="Critical Windows operating system dependency."
            )

        if service_name in self.known_bloat_services:
            info = self.known_bloat_services[service_name]
            return ServiceAuditRecord(
                service_name=service_name,
                display_name=info["display"],
                current_startup=current_startup,
                current_status=current_status,
                recommended_startup=info["recommended"],
                is_safe_to_disable=(info["recommended"] == ServiceStartupType.DISABLED),
                category=info["category"],
                reason=info["reason"]
            )

        return ServiceAuditRecord(
            service_name=service_name,
            display_name=service_name,
            current_startup=current_startup,
            current_status=current_status,
            recommended_startup=current_startup,
            is_safe_to_disable=False,
            category="Unclassified",
            reason="Service is unclassified; preserve default configuration."
        )

    def generate_rollback_script(self, audited_services: List[ServiceAuditRecord]) -> str:
        """Generate PowerShell rollback script restoring original service startup states."""
        lines = [
            "# PowerShell Service Configuration Rollback Manifest",
            "# Automatically generated by Artifact E14 Windows Optimizer",
            ""
        ]
        for svc in audited_services:
            startup_str = svc.current_startup.value.lower()
            if startup_str == "disabled":
                mode = "Disabled"
            elif startup_str == "manual":
                mode = "Manual"
            else:
                mode = "Automatic"
            lines.append(f"Set-Service -Name '{svc.service_name}' -StartupType {mode}")
        return "\n".join(lines)
